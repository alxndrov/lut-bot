"""Расшифровка цифр в ответах клиента для карточки заказа.

Клиент отвечает номером — цвета с картинки-палитры, модели микрофона,
текстуры ручки. В админском чате голая цифра ничего не говорит: приходится
держать палитру в голове. Здесь рядом с цифрой дописываем, что она значит.

Вопрос узнаём по слову в тексте, а не по позиции: вопросы правятся в
админке, и порядок может поменяться.

ВАЖНО: палитра должна совпадать с картинкой, которую видит клиент. Если
картинку перерисовали — правим и COLORS, иначе подписи будут врать.
Старые заказы не перерисовываются: подпись ставится один раз, при
создании карточки, поэтому заказы со старой палитрой (1–23) подписей не
получают и неверно не подписываются.
"""
import re

# Палитра с 01.10.2026 — 10 цветов (до этого было 23, см. память проекта)
COLORS = {
    1: "черный", 2: "розовый", 3: "красный", 4: "оливковый", 5: "синий",
    6: "розовый блестящий", 7: "фиолетовый", 8: "белый", 9: "голубой",
    10: "оранжевый",
}
MODELS = {1: "Hollyland Lark M2", 2: "DJI Mic Mini", 3: "DJI Mic"}
TEXTURES = {1: "с текстурой", 2: "гладкий"}

# Слово в тексте вопроса → какой расшифровкой подписывать ответ
_RULES = (
    ("цвет", COLORS),
    ("модел", MODELS),
    ("текстур", TEXTURES),
)

_LEADING_NUMBER = re.compile(r"^\s*(\d{1,3})(?!\d)")


def labels_for(question: str) -> dict | None:
    q = (question or "").lower()
    return next((labels for word, labels in _RULES if word in q), None)


def annotate(question: str, answer: str | None) -> str | None:
    """'2' → '2 (розовый)'. Ответ не цифрой — возвращаем как есть.

    Подписываем, только если ответ НАЧИНАЕТСЯ с числа: «1» или «1 hollyland»
    — да, «мне 2 штуки» — нет, это уже не выбор варианта. Номер, которого
    нет в списке, помечаем — скорее всего, клиент смотрел на старую палитру.
    """
    if not answer:
        return answer
    labels = labels_for(question)
    if not labels:
        return answer
    m = _LEADING_NUMBER.match(answer)
    if not m:
        return answer
    num = int(m.group(1))
    label = labels.get(num, "⚠️ нет такого варианта")
    return answer[:m.end()] + f" ({label})" + answer[m.end():]
